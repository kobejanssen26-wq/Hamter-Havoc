#!/usr/bin/env python3
"""
Generates docs/ANIMATIONS.md (the animation / action catalog) from the game's own files, so the document can never drift:

    python3 tools/ReleaseCheck/gen_animation_docs.py            # rewrite docs/ANIMATIONS.md
    python3 tools/ReleaseCheck/gen_animation_docs.py --check    # exit 1 when the document is out of date (release_check runs this)

Sources: Modules/ActionCatalog.luau (character actions), Modules/Content/Animations/*.luau (published animation slots),
Modules/Content/Items/*.luau (which weapon uses which animation / swing shape), Modules/Content/Emotes/*.luau (emotes).
It never invents ids: an animation without an AssetId is listed as "not uploaded yet".
"""
import os, re, sys, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MODULES = os.path.join(ROOT, "src", "ReplicatedStorage", "Modules")
DOC = os.path.join(ROOT, "docs", "ANIMATIONS.md")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def field(text, key):
    m = re.search(rf"\b{key} = \"([^\"]*)\"", text)
    if m:
        return m.group(1)
    m = re.search(rf"\b{key} = ([0-9.]+)", text)
    return m.group(1) if m else ""


def actions():
    text = read(os.path.join(MODULES, "ActionCatalog.luau"))
    body = text.split("ActionCatalog.List = {", 1)[1].split("\n}\n", 1)[0]
    # one entry starts on every line that begins with "{ Id = "
    lines = body.split("\n")
    current, groups = [], []
    for line in lines:
        if line.startswith("\t{ Id = "):
            if current:
                groups.append("\n".join(current))
            current = [line]
        elif current:
            current.append(line)
    if current:
        groups.append("\n".join(current))
    return groups


def animation_files():
    out = {}
    for path in sorted(glob.glob(os.path.join(MODULES, "Content", "Animations", "*.luau"))):
        if os.path.basename(path).startswith("_"):
            continue
        text = read(path)
        out[field(text, "Name")] = text
    return out


def weapons():
    rows = []
    for path in sorted(glob.glob(os.path.join(MODULES, "Content", "Items", "*.luau"))):
        if os.path.basename(path).startswith("_"):
            continue
        text = read(path)
        animation = field(text, "Animation")
        if animation:
            rows.append((field(text, "Id"), field(text, "DisplayName"), animation, field(text, "Swing") or "(default for its type)"))
    return rows


def emotes():
    rows = []
    for path in sorted(glob.glob(os.path.join(MODULES, "Content", "Emotes", "*.luau"))):
        if os.path.basename(path).startswith("_"):
            continue
        text = read(path)
        rows.append((field(text, "Id"), field(text, "DisplayName"), field(text, "Builtin"), field(text, "Animation") or field(text, "AssetId")))
    return rows


def build():
    out = []
    out.append("# Animation & action catalog\n")
    out.append("> Generated by `tools/ReleaseCheck/gen_animation_docs.py` from the game's own files. **Do not edit by hand**: change `Modules/ActionCatalog.luau` or the files in `Modules/Content/` and run the script again (`release_check.py` fails when this file is out of date).\n")
    out.append("No animation id is invented anywhere. Every action works today with a built-in procedural movement; to use your own animation, publish it in Roblox Studio (Animation Editor) and paste its `rbxassetid://` into the matching file in `Modules/Content/Animations/` - then it replaces the built-in movement automatically.\n")
    out.append("## Character actions (ActionCatalog)\n")
    out.append("The **server** announces an action only after the thing really happened (ActionFx), every client draws it (ActionAnimator). Clients cannot make other players animate.\n")
    out.append("| Stable ID | Name | Group | Built-in pose | Own animation slot | Sound | Priority | Cooldown (s) | Duration (s) | Rig | Available to | Announced by |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for chunk in actions():
        row = [field(chunk, k) for k in ("Id", "Name", "Group", "Pose", "Animation", "Sound", "Priority", "Cooldown", "Duration", "Rig", "Availability", "Trigger")]
        row = [(c if c else "-").replace("|", "/") for c in row]
        row[0] = f"`{row[0]}`"
        out.append("| " + " | ".join(row) + " |")
    out.append("")
    out.append("Rig note: the built-in poses move R15 joints. On an R6 character only the sound plays until you assign a published animation.\n")
    out.append("## Published animation slots (Modules/Content/Animations)\n")
    out.append("| Name | Rig | Use | Priority | Looped | Status |")
    out.append("|---|---|---|---|---|---|")
    for name, text in animation_files().items():
        asset = field(text, "AssetId")
        status = "assigned" if asset else "not uploaded yet (built-in movement is used)"
        out.append(f"| `{name}` | {field(text, 'Rig') or '-'} | {field(text, 'Use') or '-'} | {field(text, 'Priority') or '-'} | {'yes' if 'Looped = true' in text else 'no'} | {status} |")
    out.append("")
    out.append("## Weapons (one framework: WeaponAnimator)\n")
    out.append("Timing comes from the server's phases (`CombatTiming`: wind-up, active, recovery); the animation is only the picture. Without an AssetId the weapon's grip is swung with a built-in shape.\n")
    out.append("| Item | Name | Animation slot | Swing shape |")
    out.append("|---|---|---|---|")
    for item_id, name, animation, swing in weapons():
        out.append(f"| `{item_id}` | {name or '-'} | `{animation}` | {swing} |")
    out.append("")
    out.append("## Emotes (EmoteController)\n")
    out.append("| Id | Name | Roblox built-in | Own animation |")
    out.append("|---|---|---|---|")
    for emote_id, name, builtin, own in emotes():
        out.append(f"| `{emote_id}` | {name} | {builtin or '-'} | {own or '-'} |")
    out.append("")
    out.append("## How to add or change one\n")
    out.append("1. **New character action**: add a row to `Modules/ActionCatalog.luau` (copy a neighbour), pick an existing `Pose` (or add one to `ActionAnimator.Poses`), call `ActionFx.play(player, \"YourId\")` on the server right after the real event happened, run this script.")
    out.append("2. **Your own animation**: publish it in Studio, create `Modules/Content/Animations/<Name>.luau` from `_Template.luau` with the `AssetId`, then put its name in the action's `Animation` field (or in the weapon's `Weapon.Animation`).")
    out.append("3. **Check**: `python3 tools/ReleaseCheck/release_check.py` and the simulation `tools/SimTests/run.sh scn_actions`.")
    out.append("")
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        current = read(DOC) if os.path.exists(DOC) else ""
        if current != text:
            print("docs/ANIMATIONS.md is out of date: run python3 tools/ReleaseCheck/gen_animation_docs.py")
            sys.exit(1)
        print("docs/ANIMATIONS.md is up to date")
        return
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(DOC, ROOT))


if __name__ == "__main__":
    main()
